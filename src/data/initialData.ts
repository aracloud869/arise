export const getDailyRotatingShop = (
  dateSeedOrOwned: string | ShopItem[],
  maybeOwned?: ShopItem[]
): ShopItem[] => {
  const seed = typeof dateSeedOrOwned === 'string' ? dateSeedOrOwned : new Date().toDateString();
  const existingOwnedItems = Array.isArray(dateSeedOrOwned) ? dateSeedOrOwned : (maybeOwned || []);

  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  const absHash = Math.abs(hash);

  return ALL_ROTATING_SHOP_ITEMS.map((item, idx) => {
    const existing = existingOwnedItems.find((e) => e.id === item.id);
    const isDailySpecial = (absHash + idx) % 3 === 0;
    const discount = isDailySpecial ? 0.75 : 1.0;

    return {
      ...item,
      price: Math.round(item.price * discount),
      quantity: existing ? existing.quantity : 0,
      equipped: existing ? existing.equipped : false,
    };
  });
};

export const getDailyShopSelection = getDailyRotatingShop;

